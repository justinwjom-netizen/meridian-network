// Generates web/assets/web3.js — the client-side signing layer. Embeds the
// PolicyVault ABI + bytecode and the live testnet addresses so every on-chain
// write is signed by the CONNECTED USER'S WALLET (their approval, their gas).
// The server never signs. Re-run after a redeploy: `node scripts/gen-web3.cjs`.
const fs = require('fs');
const path = require('path');

const artifact = require(path.join(__dirname, '..', 'artifacts', 'contracts', 'PolicyVault.sol', 'PolicyVault.json'));
const deployment = require(path.join(__dirname, '..', 'deployments', 'hsktestnet.json'));

// Minimal ABI the frontend actually calls (keeps the file lean).
const ABI = [
  'function owner() view returns (address)',
  'function isPaused() view returns (bool)',
  'function policy() view returns (uint256 perTradeCap, uint256 dailyLossLimit, uint256 dailyAgentSpendCap, uint256 maxSlippageBps)',
  'function setPolicy(uint256 _perTradeCap, uint256 _dailyLossLimit, uint256 _dailyAgentSpendCap, uint256 _maxSlippageBps)',
  'function pause()',
  'function unpause()',
  'function setSessionKey(address _key, bool _isActive, uint256 _validUntil)',
  'function setAllowedToken(address _token, bool _allowed)',
  'function setAllowedPool(address _pool, bool _allowed)',
  'function setAllowedPayee(address _payee, bool _allowed)',
  'function mandateRegistry() view returns (address)',
  'function allowedTokens(address) view returns (bool)',
  'function allowedPools(address) view returns (bool)',
  'function depositToken(address token, uint256 amount)',
  'function executeSwap(address pool, address tokenIn, address tokenOut, uint256 amountIn, uint256 minAmountOut, address[] path, uint256 deadline) returns (uint256)'
];

const CONSTRUCTOR_ABI = [
  'constructor(address _mandateRegistry, uint256 _perTradeCap, uint256 _dailyLossLimit, uint256 _dailyAgentSpendCap, uint256 _maxSlippageBps)'
];

const out = `/* ============================================================================
 * Meridian — web3.js  (AUTO-GENERATED by scripts/gen-web3.cjs — do not hand-edit)
 *
 * CLIENT-SIDE SIGNING. Every on-chain write below is executed by the wallet the
 * user connected (EIP-6963), with the user's own MetaMask/wallet approval popup
 * and paid with the user's own gas. The Meridian server NEVER signs or sends a
 * transaction on the user's behalf — it only parses intent and proposes trades.
 *
 * Because the shared demo PolicyVault is owned by the deployer, owner-gated
 * actions (setPolicy / pause) require the user to own a vault. MWEB3.deployMyVault()
 * deploys a fresh PolicyVault whose owner is the connected wallet; it is then
 * remembered (per wallet) in localStorage and used for all subsequent writes.
 * ========================================================================== */
(function () {
  'use strict';

  var DEPLOYMENT = ${JSON.stringify({ chainId: deployment.chainId, contracts: deployment.contracts, config: deployment.config, tokens: deployment.tokens }, null, 2)};

  var POLICY_VAULT_ABI = ${JSON.stringify(ABI, null, 2)};
  var POLICY_VAULT_CTOR = ${JSON.stringify(CONSTRUCTOR_ABI, null, 2)};
  var POLICY_VAULT_BYTECODE = ${JSON.stringify(artifact.bytecode)};

  // USDT on this testnet is 6-decimals; policy caps are stored in base units.
  var USDT_DECIMALS = 6;

  function ethers() {
    if (!window.ethers) throw new Error('ethers.js not loaded');
    return window.ethers;
  }

  // HSK Chain testnet — the one true network for every write.
  var HSK_HEX = '0x85';            // 133
  var HSK = {
    chainId: HSK_HEX,
    chainName: 'HashKey Chain Testnet',
    nativeCurrency: { name: 'HSK', symbol: 'HSK', decimals: 18 },
    rpcUrls: ['https://testnet.hsk.xyz'],
    blockExplorerUrls: ['https://testnet-explorer.hskchain.net']
  };

  // The exact provider the user connected, exposed by site.js.
  function rawProvider() {
    var p = (window.MERIDIAN_wallet && window.MERIDIAN_wallet.getProvider && window.MERIDIAN_wallet.getProvider()) || window.__mProvider;
    if (!p) throw new Error('No wallet connected. Click "Connect Wallet" first.');
    return p;
  }

  // Guarantee the wallet is on HSK testnet before signing, adding the network
  // if the wallet doesn't know it. This stops "sent to the wrong chain" failures.
  async function ensureChain() {
    var p = rawProvider();
    var cur;
    try { cur = await p.request({ method: 'eth_chainId' }); } catch (e) { cur = null; }
    if (cur && cur.toLowerCase() === HSK_HEX) return;
    try {
      await p.request({ method: 'wallet_switchEthereumChain', params: [{ chainId: HSK_HEX }] });
    } catch (err) {
      var code = err && (err.code || (err.data && err.data.originalError && err.data.originalError.code));
      if (code === 4902 || code === -32603) {
        await p.request({ method: 'wallet_addEthereumChain', params: [HSK] });
        await p.request({ method: 'wallet_switchEthereumChain', params: [{ chainId: HSK_HEX }] });
      } else {
        throw new Error('Please switch your wallet to HashKey Chain Testnet (id 133) to continue.');
      }
    }
  }

  async function signer() {
    await ensureChain();
    var bp = new (ethers().BrowserProvider)(rawProvider());
    return await bp.getSigner();
  }

  // Address WITHOUT forcing a network switch (safe for reads / page load).
  async function connectedAddress() {
    var accts = await rawProvider().request({ method: 'eth_accounts' });
    if (!accts || !accts.length) throw new Error('No wallet connected. Click "Connect Wallet" first.');
    return accts[0];
  }

  var LS_KEY = 'meridian.userVault';
  function loadUserVaults() {
    try { return JSON.parse(localStorage.getItem(LS_KEY) || '{}'); } catch (e) { return {}; }
  }
  function saveUserVault(addr, vault) {
    try { var m = loadUserVaults(); m[addr.toLowerCase()] = vault; localStorage.setItem(LS_KEY, JSON.stringify(m)); } catch (e) {}
  }

  // Resolve which vault to write to for the connected wallet. Prefers the user's
  // own deployed vault; falls back to the shared vault for READS only.
  async function myVaultAddress() {
    var addr = (await connectedAddress()).toLowerCase();
    var m = loadUserVaults();
    return m[addr] || null;
  }

  function sharedVaultAddress() { return DEPLOYMENT.contracts.PolicyVault; }

  async function vaultContract(write) {
    var own = await myVaultAddress();
    var target = own || sharedVaultAddress();
    var runner = write ? await signer() : new (ethers().BrowserProvider)(rawProvider());
    return { contract: new (ethers().Contract)(target, POLICY_VAULT_ABI, runner), address: target, isOwn: !!own };
  }

  function usdtToBase(human) {
    return ethers().parseUnits(String(human), USDT_DECIMALS);
  }
  function baseToUsdt(base) {
    return Number(ethers().formatUnits(base, USDT_DECIMALS));
  }

  var MWEB3 = {
    deployment: DEPLOYMENT,

    async account() { return await connectedAddress(); },

    // Deploy a PolicyVault owned by the connected wallet. User approves + pays gas.
    async deployMyVault(opts) {
      opts = opts || {};
      var s = await signer();
      var cfg = DEPLOYMENT.config;
      var factory = new (ethers().ContractFactory)(POLICY_VAULT_CTOR.concat(POLICY_VAULT_ABI), POLICY_VAULT_BYTECODE, s);
      var contract = await factory.deploy(
        DEPLOYMENT.contracts.MandateRegistry,
        opts.perTradeCap != null ? usdtToBase(opts.perTradeCap) : cfg.perTradeCap,
        opts.dailyLossLimit != null ? usdtToBase(opts.dailyLossLimit) : cfg.dailyLossLimit,
        opts.dailyAgentCap != null ? usdtToBase(opts.dailyAgentCap) : cfg.dailyAgentSpendCap,
        opts.maxSlippageBps != null ? opts.maxSlippageBps : cfg.maxSlippageBps
      );
      await contract.waitForDeployment();
      var addr = await contract.getAddress();
      saveUserVault(await connectedAddress(), addr);
      return addr;
    },

    async hasVault() { return !!(await myVaultAddress()); },
    async activeVault() { return (await myVaultAddress()) || sharedVaultAddress(); },

    // Is the connected wallet the owner of the active vault?
    async isOwner() {
      var vc = await vaultContract(false);
      try {
        var o = await vc.contract.owner();
        var me = await connectedAddress();
        return o.toLowerCase() === me.toLowerCase();
      } catch (e) { return false; }
    },

    async readPolicy() {
      var vc = await vaultContract(false);
      var p = await vc.contract.policy();
      var paused = await vc.contract.isPaused();
      return {
        vault: vc.address,
        isOwn: vc.isOwn,
        perTradeCap: baseToUsdt(p.perTradeCap),
        dailyLossLimit: baseToUsdt(p.dailyLossLimit),
        dailyAgentCap: baseToUsdt(p.dailyAgentSpendCap),
        maxSlippageBps: Number(p.maxSlippageBps),
        isPaused: paused
      };
    },

    // Owner-gated write. The user's wallet signs and pays gas.
    async setPolicy(params) {
      if (!(await this.isOwner())) {
        throw new Error('You do not own this vault. Deploy your own vault first so your wallet controls policy.');
      }
      var cur = await this.readPolicy();
      var p = params || {};
      var vc = await vaultContract(true);
      var tx = await vc.contract.setPolicy(
        usdtToBase(p.perTradeCap != null ? p.perTradeCap : cur.perTradeCap),
        usdtToBase(p.dailyLossLimit != null ? p.dailyLossLimit : cur.dailyLossLimit),
        usdtToBase(p.dailyAgentCap != null ? p.dailyAgentCap : cur.dailyAgentCap),
        p.maxSlippageBps != null ? p.maxSlippageBps : cur.maxSlippageBps
      );
      var rcpt = await tx.wait();
      return rcpt.hash;
    },

    async pause() {
      if (!(await this.isOwner())) throw new Error('You do not own this vault. Deploy your own vault to control it.');
      var vc = await vaultContract(true);
      var tx = await vc.contract.pause();
      return (await tx.wait()).hash;
    },

    async unpause() {
      if (!(await this.isOwner())) throw new Error('You do not own this vault. Deploy your own vault to control it.');
      var vc = await vaultContract(true);
      var tx = await vc.contract.unpause();
      return (await tx.wait()).hash;
    },

    // One-time: allowlist the testnet trading tokens + router pool on the user's
    // own vault so executeSwap can pass policy checks. Each call is a separate
    // wallet approval signed by the user.
    async enableTrading() {
      if (!(await this.isOwner())) throw new Error('Deploy your own vault first — only its owner can enable trading.');
      var vc = await vaultContract(true);
      var t = DEPLOYMENT.tokens;
      var hashes = [];
      var tx1 = await vc.contract.setAllowedToken(t.USDT_ADDRESS, true); hashes.push((await tx1.wait()).hash);
      var tx2 = await vc.contract.setAllowedToken(t.HSK_ADDRESS, true); hashes.push((await tx2.wait()).hash);
      var tx3 = await vc.contract.setAllowedPool(t.HSKSWAP_ROUTER, true); hashes.push((await tx3.wait()).hash);
      return hashes;
    },

    // Execute a REAL swap through the user-owned vault. The user's wallet signs
    // and pays gas. Returns the real tx hash; reverts surface honestly (no fake
    // settlement). amountInUsdt is human USDT; minAmountOut is in base units.
    async executeSwap(opts) {
      if (!(await this.isOwner())) throw new Error('You must own a configured vault to execute a trade. Deploy and fund your vault first.');
      opts = opts || {};
      var t = DEPLOYMENT.tokens;
      var vc = await vaultContract(true);
      var amountIn = usdtToBase(opts.amountInUsdt != null ? opts.amountInUsdt : 100);
      var deadline = Math.floor(Date.now() / 1000) + 600;
      var path = [t.USDT_ADDRESS, t.HSK_ADDRESS];
      var tx = await vc.contract.executeSwap(
        t.HSKSWAP_ROUTER, t.USDT_ADDRESS, t.HSK_ADDRESS,
        amountIn, opts.minAmountOut != null ? opts.minAmountOut : 0n, path, deadline
      );
      return (await tx.wait()).hash;
    },

    explorerTx: function (hash) { return 'https://testnet-explorer.hskchain.net/tx/' + hash; },
    explorerAddr: function (a) { return 'https://testnet-explorer.hskchain.net/address/' + a; }
  };

  window.MWEB3 = MWEB3;
})();
`;

const dest = path.join(__dirname, '..', 'web', 'assets', 'web3.js');
fs.writeFileSync(dest, out);
console.log('Wrote', dest, '(' + out.length + ' bytes, bytecode ' + artifact.bytecode.length + ' chars)');
